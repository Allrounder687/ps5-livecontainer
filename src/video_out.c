int video_out_init(void) {
    memset(&g_video_ctx, 0, sizeof(g_video_ctx));

    /* Open default display device 0xFF */
    g_video_ctx.handle = sceVideoOutOpen(0xFF, 0, 0, NULL);
    if (g_video_ctx.handle < 0) {
        lc_log("[VideoOut] sceVideoOutOpen returned: %d", g_video_ctx.handle);
        return -1;
    }

    size_t fb_size = SCREEN_WIDTH * SCREEN_HEIGHT * sizeof(uint32_t);
    for (int i = 0; i < NUM_BUFFERS; i++) {
        g_video_ctx.framebuffers[i] = (uint32_t *)mmap(NULL, fb_size,
            PROT_READ | PROT_WRITE, MAP_PRIVATE | MAP_ANON, -1, 0);
        if (g_video_ctx.framebuffers[i] == MAP_FAILED) {
            lc_log("[VideoOut] Failed to allocate framebuffer %d", i);
            return -1;
        }
        memset(g_video_ctx.framebuffers[i], 0x11, fb_size);
    }

    /* Register display buffers with PS5 VideoOut driver */
    int reg_res = sceVideoOutRegisterBuffers(g_video_ctx.handle, 0,
        (void * const *)g_video_ctx.framebuffers, NUM_BUFFERS, NULL);

    lc_log("[VideoOut] sceVideoOutRegisterBuffers returned: %d", reg_res);
    g_video_ctx.is_initialized = 1;
    return 0;
}

void video_out_clear(uint32_t color) {
    if (!g_video_ctx.is_initialized) return;
    uint32_t *fb = g_video_ctx.framebuffers[g_video_ctx.current_buffer_idx];
    for (int i = 0; i < SCREEN_WIDTH * SCREEN_HEIGHT; i++) {
        fb[i] = color;
    }
}

void video_out_draw_rect(int x, int y, int w, int h, uint32_t color) {
    if (!g_video_ctx.is_initialized) return;
    uint32_t *fb = g_video_ctx.framebuffers[g_video_ctx.current_buffer_idx];
    for (int dy = 0; dy < h; dy++) {
        int py = y + dy;
        if (py < 0 || py >= SCREEN_HEIGHT) continue;
        for (int dx = 0; dx < w; dx++) {
            int px = x + dx;
            if (px < 0 || px >= SCREEN_WIDTH) continue;
            fb[py * SCREEN_WIDTH + px] = color;
        }
    }
}

static void draw_char(int x, int y, char c, uint32_t color, int scale) {
    if ((uint8_t)c > 127) c = '?';
    uint32_t *fb = g_video_ctx.framebuffers[g_video_ctx.current_buffer_idx];
    const uint8_t *glyph = FONT8x8_BASIC[(uint8_t)c];

    for (int r = 0; r < 8; r++) {
        uint8_t row = glyph[r];
        for (int col = 0; col < 8; col++) {
            if (row & (1 << (7 - col))) {
                for (int sy = 0; sy < scale; sy++) {
                    int py = y + r * scale + sy;
                    if (py < 0 || py >= SCREEN_HEIGHT) continue;
                    for (int sx = 0; sx < scale; sx++) {
                        int px = x + col * scale + sx;
                        if (px < 0 || px >= SCREEN_WIDTH) continue;
                        fb[py * SCREEN_WIDTH + px] = color;
                    }
                }
            }
        }
    }
}

void video_out_draw_string(int x, int y, const char *str, uint32_t color) {
    if (!str || !g_video_ctx.is_initialized) return;
    int scale = 3; /* 24x24 px readable on 4K/1080p TVs */
    int cx = x;
    while (*str) {
        if (*str == '\n') {
            y += 8 * scale + 6;
            cx = x;
        } else {
            draw_char(cx, y, *str, color, scale);
            cx += 8 * scale + 2;
        }
        str++;
    }
}

