void video_out_flip(void) {
    if (!g_video_ctx.is_initialized) return;

    /* Submit current buffer for display flip */
    sceVideoOutSubmitFlip(g_video_ctx.handle, g_video_ctx.current_buffer_idx, 0, g_video_ctx.flip_arg++);
    sceVideoOutWaitVblank(g_video_ctx.handle);

    /* Switch to next double-buffer */
    g_video_ctx.current_buffer_idx = (g_video_ctx.current_buffer_idx + 1) % NUM_BUFFERS;
}

void video_out_cleanup(void) {
    if (g_video_ctx.handle >= 0) {
        sceVideoOutClose(g_video_ctx.handle);
        g_video_ctx.handle = -1;
    }
}
